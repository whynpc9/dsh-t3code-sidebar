// Regenerate src/domain/chinese-variants.ts from OpenCC's traditional →
// simplified character table (TSCharacters.txt, Apache-2.0).
// Usage: pnpm run variants:update [-- local TSCharacters.txt]
// Without an argument it downloads the table from OpenCC's master branch.
// The download is untrusted data: every line is strictly checked, and any
// surprise fails the run instead of writing a partial file.
import { readFileSync, writeFileSync } from 'node:fs'

const OUTPUT = new URL('../src/domain/chinese-variants.ts', import.meta.url)
const SOURCE = 'https://github.com/BYVoid/OpenCC'
const RAW = 'https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary/TSCharacters.txt'
const HAN = /^\p{Script=Han}$/u

function fail(message) {
  console.error(`update-chinese-variants: ${message}`)
  process.exit(1)
}

const local = process.argv[2]
let text
if (local !== undefined) {
  text = readFileSync(local, 'utf8')
} else {
  const response = await fetch(RAW)
  if (!response.ok) fail(`download failed: HTTP ${response.status}`)
  text = await response.text()
}

const pairs = new Map()
let skipped = 0
for (const [index, raw] of text.split('\n').entries()) {
  const line = raw.trimEnd()
  if (line === '' || line.startsWith('#')) continue
  const match = /^(\S+)\t(\S+(?: \S+)*)$/.exec(line)
  if (match === null) fail(`line ${index + 1}: unexpected format ${JSON.stringify(line.slice(0, 40))}`)
  const [, from, values] = match
  // OpenCC's default conversion takes the first candidate.
  const to = values.split(' ')[0]
  if (!HAN.test(from) || !HAN.test(to)) fail(`line ${index + 1}: not one Han character each`)
  if (pairs.has(from)) fail(`line ${index + 1}: duplicate key ${from}`)
  // Folding must keep UTF-16 positions: only pairs of equal length.
  if (from === to || from.length !== to.length) { skipped += 1; continue }
  pairs.set(from, to)
}
if (pairs.size < 2000) fail(`only ${pairs.size} pairs: refusing to write a suspiciously small table`)

const sorted = [...pairs].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
const from = sorted.map(([key]) => key).join('')
const to = sorted.map(([, value]) => value).join('')
const output = `/**
 * GENERATED by scripts/update-chinese-variants.mjs. Do not edit by hand.
 *
 * Traditional → simplified Chinese characters (first candidate of each entry),
 * from OpenCC's TSCharacters.txt: ${SOURCE} (${RAW})
 * Copyright (c) OpenCC contributors. Licensed under the Apache License, Version 2.0:
 * https://www.apache.org/licenses/LICENSE-2.0
 * Only pairs of equal UTF-16 length are kept, so folding never moves positions
 * (${skipped} entries skipped).
 */

/** ${pairs.size} traditional characters; \`SIMPLIFIED\` holds their simplified forms in the same order. */
export const TRADITIONAL = ${JSON.stringify(from)}
export const SIMPLIFIED = ${JSON.stringify(to)}
`
writeFileSync(OUTPUT, output)
console.log(`wrote ${pairs.size} pairs (${skipped} skipped) to src/domain/chinese-variants.ts`)
